test('the session answers the token once with no-store and stores no copy', async (t) => {
  exchange(t);
  const db = driveDatabase();
  arrange({ db });

  const { answer, output } = await captured(() => mint());

  assert.equal(answer.status, 200);
  assert.equal(answer.cacheControl, 'no-store');
  assert.deepEqual(answer.body, {
    accessToken: TOKEN,
    expiresAt: answer.body.expiresAt,
    apiKey: KEY,
    appId: PROJECT,
  });
  const expiry = Date.parse(answer.body.expiresAt);
  assert.ok(expiry > Date.now() + 3_000_000);
  assert.ok(expiry <= Date.now() + 3_605_000);
  // The answer is the only place that holds the token.
  assert.ok(
    !output.includes(TOKEN),
    'The token must not reach the process output.',
  );
  assert.ok(![...activeCache.entries.values()].some((v) => v.includes(TOKEN)));
  const reads = statements(db, 'cc.device_write_credential');
  assert.equal(reads.length, 1);
  assert.deepEqual(reads[0][1], [
    ACTOR,
    PERMISSION_VERSION,
    CUSTOMER,
    GENERATION,
  ]);
});

