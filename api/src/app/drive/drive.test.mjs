test('the tab list answers the tabs of one Sheet with the person token', async (t) => {
  exchange(t);
  const db = driveDatabase();
  arrange({ db });
  const sent = [];
  const transporter = Object.getPrototypeOf(new OAuth2Client().transporter);
  t.mock.method(transporter, 'request', async (options) => {
    const url = new URL(options.url);
    sent.push({
      path: url.pathname,
      authorization: options.headers.get('authorization'),
    });
    if (url.pathname === `/drive/v3/files/${SHEET_ID}`)
      return {
        status: 200,
        headers: new Headers(),
        data: {
          name: 'Devices',
          mimeType: 'application/vnd.google-apps.spreadsheet',
          modifiedTime: NOW,
        },
      };
    return {
      status: 200,
      headers: new Headers(),
      data: {
        sheets: [{ properties: { sheetId: 0, title: 'Devices', index: 0 } }],
      },
    };
  });

  const { answer, output } = await captured(() => tabs(SHEET_ID));

  assert.equal(answer.status, 200);
  assert.equal(answer.cacheControl, 'no-store');
  assert.deepEqual(answer.body, {
    fileId: SHEET_ID,
    tabs: [{ tabId: 0, title: 'Devices', index: 0 }],
  });
  assert.deepEqual(
    sent.map((item) => item.path),
    [`/drive/v3/files/${SHEET_ID}`, `/v4/spreadsheets/${SHEET_ID}`],
  );
  assert.deepEqual(
    sent.map((item) => item.authorization),
    [`Bearer ${TOKEN}`, `Bearer ${TOKEN}`],
  );
  assert.ok(!output.includes(TOKEN));
  assert.deepEqual([...activeCache.entries.keys()], []);
});

